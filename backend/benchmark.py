"""
shieldAI engine accuracy benchmark.

Runs each analysis engine over the labeled synthetic dataset in benchmark_data/
and reports precision / recall / F1 / accuracy per engine across risk thresholds.

Usage:  python benchmark.py   (from the backend/ directory)
"""
import json
import os
import sys

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "benchmark_data")
REPORT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "BENCHMARKS.md")

from app.cv_engine import perform_ela
from app.video_engine import analyze_video
from app.audio_engine import analyze_audio
from app.url_engine import analyze_url

THRESHOLDS = [30, 40, 50, 60, 70]


def load_files(subdir: str):
    base = os.path.join(DATA_DIR, subdir)
    files = []
    for root, _dirs, names in os.walk(base):
        for name in sorted(names):
            path = os.path.join(root, name)
            with open(path, "rb") as f:
                files.append((name, f.read()))
    return files


def evaluate(name: str, samples, score_fn):
    """samples: list of (label_bool, *args). score_fn(*args) -> (risk, extra_dict)."""
    rows = []
    for label, *args in samples:
        risk, extra = score_fn(*args)
        rows.append({"name": args[0] if args else "", "label": bool(label), "risk": float(risk), **extra})

    print(f"\n=== {name} ({len(rows)} samples) ===")
    for r in rows:
        print(f"  {r['name']:<45} truth={'MOD' if r['label'] else 'OK ':>3} risk={r['risk']:>6.1f}")

    results = {}
    for t in THRESHOLDS:
        tp = sum(1 for r in rows if r["label"] and r["risk"] >= t)
        fp = sum(1 for r in rows if not r["label"] and r["risk"] >= t)
        fn = sum(1 for r in rows if r["label"] and r["risk"] < t)
        tn = sum(1 for r in rows if not r["label"] and r["risk"] < t)
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / (tp + fn) if tp + fn else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        accuracy = (tp + tn) / len(rows) if rows else 0.0
        results[t] = {
            "tp": tp, "fp": fp, "fn": fn, "tn": tn,
            "precision": precision, "recall": recall, "f1": f1, "accuracy": accuracy,
        }
    best_t = max(results, key=lambda t: results[t]["f1"])
    return rows, results, best_t


def main():
    image_samples = [("modified" in n, n, b) for n, b in load_files("image")]
    video_samples = [("modified" in n, n, b) for n, b in load_files("video")]
    audio_samples = [("modified" in n, n, b) for n, b in load_files("audio")]
    with open(os.path.join(DATA_DIR, "urls.json"), encoding="utf-8") as f:
        url_rows = json.load(f)
    url_samples = [(u["malicious"], u["url"]) for u in url_rows]

    def score_image(name, b):
        _ela, risk, _anom = perform_ela(b)
        return risk, {}

    def score_video(name, b):
        r = analyze_video(name, b)
        return r["risk_score"], {"level": r["risk_level"]}

    def score_audio(name, b):
        r = analyze_audio(name, b)
        return r["risk_score"], {"level": r["risk_level"]}

    def score_url(url):
        r = analyze_url(url)
        return r["risk_score"], {"level": r["risk_level"]}

    engines = {
        "Image (ELA / tamper)": (image_samples, score_image),
        "Video (frame ELA / re-encode)": (video_samples, score_video),
        "Audio (prosody / synthetic voice)": (audio_samples, score_audio),
        "URL (lexical / typosquat)": (url_samples, score_url),
    }

    all_results = {}
    for name, (samples, fn) in engines.items():
        rows, results, best_t = evaluate(name, samples, fn)
        all_results[name] = {"rows": rows, "results": results, "best_t": best_t}

    lines = [
        "# shieldAI Engine Accuracy Benchmarks",
        "",
        "Generated by `backend/benchmark.py` against the labeled synthetic dataset in `backend/benchmark_data/`.",
        "",
        "> **Dataset honesty note**: samples are procedurally generated (synthetic scenes, test patterns,",
        "> synthesized speech) designed to exercise each engine's claimed signal types. These numbers are",
        "> **calibration indicators, not proof of real-world accuracy**. Validation against genuine",
        "> deepfakes, AI-generated images, real voice recordings, and live phishing domains is required",
        "> before any public accuracy claims.",
        "",
        "| Engine | Threshold | Precision | Recall | F1 | Accuracy | TP | FP | FN | TN |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, data in all_results.items():
        for t, m in data["results"].items():
            lines.append(
                f"| {name} | {t} | {m['precision']:.2f} | {m['recall']:.2f} | {m['f1']:.2f} "
                f"| {m['accuracy']:.2f} | {m['tp']} | {m['fp']} | {m['fn']} | {m['tn']} |"
            )

    lines.append("")
    lines.append("## Per-sample scores")
    lines.append("")
    for name, data in all_results.items():
        lines.append(f"### {name}")
        lines.append("")
        lines.append("| Sample | Truth | Risk | Notes |")
        lines.append("|---|---|---|---|")
        for r in data["rows"]:
            truth = "MODIFIED" if r["label"] else "clean"
            note = r.get("level", "")
            lines.append(f"| {r['name']} | {truth} | {r['risk']:.1f} | {note} |")
        lines.append("")

    lines.append("")
    lines.append("## Recommended thresholds (best F1 on this dataset)")
    lines.append("")
    for name, data in all_results.items():
        lines.append(f"- **{name}**: {data['best_t']}")

    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"\nReport written to {os.path.normpath(REPORT_PATH)}")


if __name__ == "__main__":
    main()
